// QA-A18 + contract 1.10.0, live: Regenerate keeps the earlier answer (‹ 1/2 ›, under the answer);
// "Answer style → More concise" adds 3/3 with a "Concise" chip; arrows switch; reload keeps all versions.
// Usage: node scripts/e2e_answer_versions.mjs [baseUrl] [outDir]
import { chromium } from 'playwright';
import fs from 'node:fs';
const [base = 'http://127.0.0.1:5211/', out = '/workspace/cc_fe/shots/answer/e3'] = process.argv.slice(2);
fs.mkdirSync(out, { recursive: true });
const exe = fs.existsSync('/usr/bin/google-chrome') ? '/usr/bin/google-chrome' : undefined;
const browser = await chromium.launch({ executablePath: exe, headless: true });
const pg = await (await browser.newContext({ viewport: { width: 1024, height: 760 } })).newPage();
const errors = [], bodies = [];
pg.on('pageerror', (e) => errors.push(String(e)));
pg.on('request', (r) => { if (r.method() === 'POST' && new URL(r.url()).pathname === '/api/chat') bodies.push(r.postDataJSON()?.regenerate ?? null); });
const box = () => pg.getByRole('textbox', { name: 'Message' });
const idle = () => pg.getByRole('button', { name: 'Send message' }).waitFor({ timeout: 120000 });
const last = () => pg.getByTestId('msg-assistant').last();
const nav = async () => (await last().getByTestId('version-nav').textContent().catch(() => null))?.trim() ?? null;
await pg.goto(base, { timeout: 90000 });
await box().waitFor({ timeout: 90000 });
await box().fill('What is the denial rate by payer?');
await pg.keyboard.press('Enter');
await idle();
const firstText = (await last().innerText()).slice(0, 60);
await last().getByRole('button', { name: 'Regenerate' }).click();
await idle();
const afterRegen = await nav();
await last().getByTestId('regenerate-menu-button').click();
await pg.screenshot({ path: `${out}/v_01_style_menu.png` });
await pg.getByRole('menuitem', { name: /More concise/ }).click();
await idle();
const afterConcise = await nav();
const chip = await last().getByTestId('regen-style').textContent().catch(() => null);
await pg.screenshot({ path: `${out}/v_02_concise_3of3.png` });
await last().getByRole('button', { name: 'Previous version' }).click();
await last().getByRole('button', { name: 'Previous version' }).click();
const backTo1 = await nav();
const userNav = await pg.getByTestId('msg-user').last().getByTestId('version-nav').count();
await pg.screenshot({ path: `${out}/v_03_back_to_1of3.png` });
await pg.waitForTimeout(500);
await pg.reload();
await last().getByTestId('version-nav').waitFor({ timeout: 30000 });
const afterReload = await nav();
const chipReload = await last().getByTestId('regen-style').textContent().catch(() => null);
await last().getByRole('button', { name: 'Previous version' }).click();
const reloadPrev = await nav();
await pg.screenshot({ path: `${out}/v_04_reload.png` });
console.log(JSON.stringify({ firstText: firstText.replace(/\s+/g, ' '), afterRegen, afterConcise, chip, backTo1, userNav, afterReload, chipReload, reloadPrev, regenBodies: bodies, errors }, null, 1));
await browser.close();
