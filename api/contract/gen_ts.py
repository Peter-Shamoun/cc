"""Generate web/src/contract/v1.gen.ts from api/contract/v1.schema.json (the single source of truth).

    python -m api.contract.gen_ts          # write
    python -m api.contract.gen_ts --check  # exit 1 if the checked-in TS has drifted (run in CI / pytest)

Supports the schema subset the contract uses: $ref, const, enum, x-open (open string enums),
type (incl. [..., null]), arrays, objects, allOf [PartBase, {...}] (-> extends), oneOf (-> union),
and x-ts (raw TypeScript override).
"""
from __future__ import annotations

import json
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
SCHEMA = Path(__file__).with_name("v1.schema.json")
OUT = ROOT / "web" / "src" / "contract" / "v1.gen.ts"


def _ref(s: dict) -> str:
    return s["$ref"].rsplit("/", 1)[-1]


def ts(s: dict, indent: str = "") -> str:
    if "x-ts" in s:
        return s["x-ts"]
    if "$ref" in s:
        return _ref(s)
    if "const" in s:
        return json.dumps(s["const"]).replace('"', "'")
    for k in ("oneOf", "anyOf"):
        if k in s:
            return " | ".join(ts(x, indent) for x in s[k])
    if "enum" in s:
        return " | ".join(json.dumps(v).replace('"', "'") for v in s["enum"])
    if s.get("x-open"):
        return " | ".join([*(f"'{v}'" for v in s["x-known"]), "(string & {})"])
    t = s.get("type")
    if isinstance(t, list):
        return " | ".join(dict.fromkeys(ts({**s, "type": x}, indent) for x in t))
    if t == "string":
        return "string"
    if t in ("integer", "number"):
        return "number"
    if t == "boolean":
        return "boolean"
    if t == "null":
        return "null"
    if t == "array":
        inner = ts(s.get("items", {}), indent)
        return f"({inner})[]" if "|" in inner else f"{inner}[]"
    if t == "object" and "properties" in s:
        return "{\n" + _props(s, indent + "  ") + indent + "}"
    if t == "object":
        ap = s.get("additionalProperties")
        return f"Record<string, {ts(ap, indent) if isinstance(ap, dict) else 'unknown'}>"
    return "unknown"


def _doc(s: dict, indent: str) -> str:
    d = s.get("description")
    return f"{indent}/** {d} */\n" if d else ""


def _props(s: dict, indent: str) -> str:
    req = set(s.get("required", []))
    out = ""
    for name, p in s["properties"].items():
        out += _doc(p, indent) + f"{indent}{name}{'' if name in req else '?'}: {ts(p, indent)};\n"
    return out


def _kinds(schema: dict, s: dict, depth: int = 0) -> list[str]:
    """JSON kinds a value may have: string, number, integer, boolean, object, array, null. [] means any."""
    if depth > 8:
        return []
    if "$ref" in s:
        return _kinds(schema, schema["$defs"][_ref(s)], depth + 1)
    if "const" in s or "enum" in s:
        vals = [s["const"]] if "const" in s else s["enum"]
        return sorted({{str: "string", bool: "boolean", int: "integer", float: "number", type(None): "null"}.get(type(v), "any")
                       for v in vals})
    for key in ("oneOf", "anyOf"):
        if key in s:
            parts = [_kinds(schema, x, depth + 1) for x in s[key]]
            return [] if any(not p for p in parts) else sorted({k for p in parts for k in p})
    t = s.get("type")
    if t is None:
        return []
    return sorted(t) if isinstance(t, list) else [t]


def event_shape(schema: dict, name: str) -> dict:
    d = schema["$defs"][name]
    return {f: _kinds(schema, d["properties"].get(f, {})) for f in d.get("required", []) if f not in ("type", "seq")}


def open_enums(schema: dict) -> dict:
    """1.13.0: every ``x-open`` node, keyed by ``Def.field.sub`` path: {fallback} for open enums, {known} for strings."""
    out: dict = {}

    def walk(node, path):
        if not isinstance(node, dict):
            return
        if node.get("x-open"):
            out[path] = {"fallback": node["x-fallback"]} if "enum" in node else {"known": list(node.get("x-known", []))}
        for k, v in node.get("properties", {}).items():
            walk(v, f"{path}.{k}")
        if isinstance(node.get("items"), dict):
            walk(node["items"], path)

    for name, d in schema["$defs"].items():
        walk(d, name)
    return out


def generate(schema: dict) -> str:
    version = schema["version"]
    lines = ["/* eslint-disable */",
             "// GENERATED by `python -m api.contract.gen_ts` from api/contract/v1.schema.json. DO NOT EDIT.",
             "// Change the schema, bump the version (CONTRACT.md §0), and regenerate. CI fails on drift.",
             "",
             f"export const CONTRACT_VERSION = '{version}';",
             ""]
    for name, s in schema["$defs"].items():
        lines.append(_doc(s, "").rstrip("\n")) if s.get("description") else None
        if "allOf" in s:
            base, body = s["allOf"]
            lines.append(f"export interface {name} extends {_ref(base)} {{\n{_props(body, '  ')}}}")
        elif s.get("type") == "object" and "properties" in s and "x-ts" not in s:
            lines.append(f"export interface {name} {{\n{_props(s, '  ')}}}")
        else:
            lines.append(f"export type {name} = {ts(s)};")
        lines.append("")
    parts = [_ref(r) for r in schema["$defs"]["Part"]["oneOf"]]
    events = [_ref(r) for r in schema["$defs"]["StreamEvent"]["oneOf"]]
    known_parts = [schema["$defs"][p]["properties"]["type"]["const"] for p in parts]
    known_events = [schema["$defs"][e]["properties"]["type"]["const"] for e in events]
    lines.append("export const KNOWN_PART_TYPES = [" + ", ".join(f"'{p}'" for p in known_parts) + "] as const;")
    lines.append("export const KNOWN_EVENT_TYPES = [" + ", ".join(f"'{e}'" for e in known_events) + "] as const;")
    shapes = {schema["$defs"][e]["properties"]["type"]["const"]: event_shape(schema, e) for e in events}
    lines.append("/** 1.12.0: required fields of each event and their JSON kinds, for `wellFormed()` (fail-safe reducer input). */")
    lines.append("export const EVENT_SHAPES: Record<string, Record<string, readonly string[]>> = "
                 + json.dumps(shapes, separators=(", ", ": ")) + ";")
    opens = open_enums(schema)
    lines.append("/** 1.13.0: enums a newer server may extend (CONTRACT.md §3). Render an unknown value as `fallback`. */")
    lines.append("export const OPEN_ENUM_FALLBACKS: Record<string, string> = "
                 + json.dumps({k: v["fallback"] for k, v in opens.items() if "fallback" in v}, separators=(", ", ": "))
                 + ";")
    lines.append("/** 1.13.0: open string fields and the values known in this version. Anything else is valid. */")
    lines.append("export const OPEN_KNOWN_VALUES: Record<string, readonly string[]> = "
                 + json.dumps({k: v["known"] for k, v in opens.items() if "known" in v}, separators=(", ", ": "))
                 + ";")
    if "PlotSpec" in schema["$defs"]:
        d = schema["$defs"]
        plot = {"version": d["PlotSpec"]["properties"]["v"]["const"], "kinds": d["PlotKind"]["enum"],
                "fieldTypes": d["PlotFieldType"]["enum"], "formats": d["PlotFormat"]["enum"],
                "sorts": d["PlotSort"]["enum"], "temporalPattern": d["PlotSpec"]["x-temporal"], "fieldPattern": d["PlotAxisX"]["properties"]["field"]["pattern"],
                "caps": d["PlotSpec"]["x-caps"]}
        lines.append("/** 1.18.0: PlotSpec enums and caps, for the zod mirror in web/src/contract/plot.ts (one source). */")
        lines.append("export const PLOT_SCHEMA = " + json.dumps(plot, separators=(", ", ": "), ensure_ascii=False)
                     + " as const;")
    lines.append("export type PartType = Part['type'];")
    lines.append("export type StreamEventType = StreamEvent['type'];")
    return "\n".join(lines) + "\n"


RULES = Path(__file__).with_name("stream_rules.json")
RULES_OUT = ROOT / "web" / "src" / "contract" / "streamRules.gen.ts"


def generate_rules(rules: dict) -> str:
    """1.12.0: embed stream_rules.json for web/src/contract/conformance.ts (one source of rules, two runners)."""
    return ("// GENERATED by `python -m api.contract.gen_ts` from api/contract/stream_rules.json. DO NOT EDIT.\n"
            "// Edit the JSON, then regenerate. CI fails on drift.\n"
            "/* eslint-disable */\n"
            f"export const STREAM_RULES = {json.dumps(rules, indent=2, ensure_ascii=False)} as const;\n")


def main(argv: list[str]) -> int:
    outputs = {OUT: generate(json.loads(SCHEMA.read_text())),
               RULES_OUT: generate_rules(json.loads(RULES.read_text()))}
    if "--check" in argv:
        stale = [p for p, text in outputs.items() if (p.read_text() if p.exists() else "") != text]
        for p in stale:
            print(f"{p.relative_to(ROOT)} is out of date; run: python -m api.contract.gen_ts", file=sys.stderr)
        return 1 if stale else 0
    for p, text in outputs.items():
        p.parent.mkdir(parents=True, exist_ok=True)
        p.write_text(text)
        print(f"wrote {p.relative_to(ROOT)}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main(sys.argv[1:]))
